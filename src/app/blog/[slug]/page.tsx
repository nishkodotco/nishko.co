import type { Metadata } from "next";
import Link from "next/link";
import { notFound } from "next/navigation";
import { formatDate, getPost, getPostHtml, getPosts } from "@/lib/blogs";

// Only the posts in the blogs repo exist; anything else is a 404.
export const dynamicParams = false;

export function generateStaticParams() {
  const params = getPosts().map((post) => ({ slug: post.slug }));
  // `output: export` refuses an empty list; with no posts, emit one 404 page instead.
  return params.length > 0 ? params : [{ slug: "_" }];
}

export async function generateMetadata(props: PageProps<"/blog/[slug]">): Promise<Metadata> {
  const { slug } = await props.params;
  const post = getPost(slug);
  if (!post) return {};
  return {
    title: post.title,
    description: post.summary,
    openGraph: { type: "article", title: post.title, description: post.summary, publishedTime: post.date },
  };
}

export default async function PostPage(props: PageProps<"/blog/[slug]">) {
  const { slug } = await props.params;
  const post = getPost(slug);
  if (!post) notFound();

  // Other places to read this post. Add more sources here.
  const sources = [{ label: "Read as PDF", href: post.pdfUrl, icon: <PdfIcon /> }];

  const sourceLinks = sources.map((source) => (
    <a
      key={source.href}
      href={source.href}
      target="_blank"
      rel="noreferrer"
      aria-label={source.label}
      title={source.label}
      className="rounded-full p-2 text-muted-foreground transition-colors hover:bg-muted hover:text-cinnabar"
    >
      {source.icon}
    </a>
  ));

  return (
    <article className="mx-auto max-w-2xl px-4 py-12 sm:px-6 sm:py-16">
      <Link href="/blog" className="text-sm text-muted-foreground transition-colors hover:text-foreground">
        ← All posts
      </Link>

      <header className="mt-8 border-b border-border pb-8">
        <h1 className="text-4xl font-bold tracking-tight text-balance">{post.title}</h1>
        {post.summary && <p className="post-lede mt-4">{post.summary}</p>}
        <div className="mt-4 flex flex-wrap items-center justify-between gap-3">
          <p className="flex flex-wrap items-center gap-x-2 text-sm text-muted-foreground">
            <time dateTime={post.date}>{formatDate(post.date)}</time>
            <span aria-hidden>·</span>
            <span>{post.readingMinutes} min read</span>
            {post.updated !== post.date && (
              <>
                <span aria-hidden>·</span>
                <span>
                  Updated <time dateTime={post.updated}>{formatDate(post.updated)}</time>
                </span>
              </>
            )}
          </p>
          <nav aria-label="Read elsewhere" className="flex items-center gap-1 md:hidden">
            {sourceLinks}
          </nav>
        </div>
      </header>

      <div className="relative">
        {/* Right-hand rail beside the text; stays in view while scrolling. */}
        <aside className="absolute left-full top-0 hidden h-full pl-2 pt-6 md:block">
          <nav aria-label="Read elsewhere" className="sticky top-8 flex flex-col gap-1">
            {sourceLinks}
          </nav>
        </aside>

        {/* HTML generated by pandoc from my own LaTeX in blogs-latex. */}
        <div className="post-body pt-8" dangerouslySetInnerHTML={{ __html: getPostHtml(post) }} />
      </div>
    </article>
  );
}

function PdfIcon() {
  return (
    <svg viewBox="0 0 24 24" width="20" height="20" fill="none" stroke="currentColor" strokeWidth="1.75" strokeLinecap="round" strokeLinejoin="round" aria-hidden>
      <path d="M14 2H6a2 2 0 0 0-2 2v16a2 2 0 0 0 2 2h12a2 2 0 0 0 2-2V8z" />
      <path d="M14 2v6h6" />
      <text x="12" y="17.5" textAnchor="middle" fontSize="6" fontWeight="700" fill="currentColor" stroke="none" fontFamily="sans-serif">PDF</text>
    </svg>
  );
}
